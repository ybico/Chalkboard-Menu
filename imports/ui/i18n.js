export const translate = (language, key, params = {}) => {
  const template = translations[language]?.[key] ?? translations.en[key] ?? key;
  if (typeof template !== "string") return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
};

export const retranslateMessage = (fromLanguage, toLanguage, message) => {
  if (!message) return message;
  const source = translations[fromLanguage];
  const target = translations[toLanguage];
  const key = Object.keys(source).find(
    (candidate) => typeof source[candidate] === "string" && source[candidate] === message,
  );
  return key && typeof target[key] === "string" ? target[key] : message;
};

