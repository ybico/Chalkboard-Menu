export const translateError = (language, error, fallbackKey = "error.generic") => {
  if (error?.error === "admin-required") return translate(language, "error.admin.missing");
  if (error?.error === "account-disabled") return translate(language, "error.disabled");
  if (error?.error === "duplicate-user") return translate(language, "error.duplicate");
  if (error?.error === "not-authorized") return translate(language, "error.not.authorized");
  if (error?.error === "not-found") return translate(language, "error.not.found");
  if (fallbackKey === "password.failure" &&
      (error?.reason?.toLowerCase().includes("incorrect") || error?.reason?.toLowerCase().includes("password"))) {
    return translate(language, "error.password.current");
  }
  const key = reasonKeys[error?.reason];
  if (key) return translate(language, key);
  if (error?.error === "invalid-item") return translate(language, "error.invalid.item");
  if (error?.error === "invalid-user") return translate(language, "error.invalid.user");
  if (error?.error === 403 || error?.reason?.toLowerCase().includes("incorrect") ||
      error?.reason?.toLowerCase().includes("credentials")) {
    return translate(language, "error.credentials");
  }
  return translate(language, fallbackKey);
};

